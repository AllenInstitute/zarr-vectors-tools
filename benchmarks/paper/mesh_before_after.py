#!/usr/bin/env python
"""Before/after tables for the mesh read path, from two sweeps of one script.

    python mesh_before_after.py                       # results/mesh_precomputed/
    python mesh_before_after.py --root path/to/dir    # holds before/ and after/

Each side is a ``run_sweep.py`` run of the ``timing``, ``chunks``,
``fragments`` and ``mesh_precomputed`` blocks against one zarr-vectors
install -- ``before/`` against the one whose ``read_mesh`` could not scope
by object, ``after/`` against the one that can -- and their
``environment.json`` files say which.  This writes ``summary.md`` beside
them: the precomputed comparison at every N, then the existing mesh
series side by side.  Nothing is re-measured.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent / "results" / "mesh_precomputed"

IMPL_ORDER = [
    "zarr-vectors (zstd)",
    "zarr-vectors (zstd, sharded)",
    "zarr-vectors (no codec)",
    "zarr-vectors (no codec, sharded)",
    "precomputed mesh",
    "precomputed mesh (sharded)",
    "precomputed mesh (sharded, gzip)",
]


def _ms(v) -> str:
    return "—" if pd.isna(v) else (f"{v * 1e3:,.2f}" if v < 0.1 else f"{v * 1e3:,.0f}")


def _num(v, unit="") -> str:
    return "—" if pd.isna(v) else f"{v:,.0f}{unit}"


def _load(side: Path) -> tuple[pd.DataFrame, dict]:
    df = pd.read_csv(side / "measurements.csv")
    env = json.loads((side / "environment.json").read_text())
    return df, env


def _pick(df, block, op, impl=None):
    sel = (df["block"] == block) & (df["op"] == op) & (df["geometry"] == "meshes")
    if impl is not None:
        sel &= df["impl"] == impl
    return df[sel]


def precomputed_table(before, after, n) -> list[str]:
    rows = [
        f"#### N = {n:,} vertices",
        "",
        "| implementation | read one, before (ms) | read one, after (ms) "
        "| requests before → after | bytes before → after | read all (ms, after) "
        "| write (ms, after) | on disk (after) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for impl in IMPL_ORDER:
        def val(df, op, _impl=impl):
            hit = _pick(df, "mesh_precomputed", op, _impl)
            hit = hit[hit["n_target"] == n]
            return float(hit["value"].iloc[0]) if len(hit) else float("nan")

        def pair(op):
            return f"{_num(val(before, op))} → {_num(val(after, op))}"

        req, byt = pair("fetch_one_requests"), pair("fetch_one_bytes")
        if impl.startswith("precomputed"):
            # Same code on both sides; the before column is a control.
            req = _num(val(after, "fetch_one_requests"))
            byt = _num(val(after, "fetch_one_bytes"))
        rows.append(
            f"| {impl} | {_ms(val(before, 'fetch_one'))} | {_ms(val(after, 'fetch_one'))} "
            f"| {req} | {byt} | {_ms(val(after, 'read_full'))} "
            f"| {_ms(val(after, 'write_full'))} | {_num(val(after, 'bytes'), ' B')} |"
        )
    return rows + [""]


def series_table(before, after, block, op, key, label) -> list[str]:
    b = _pick(before, block, op, "zarr-vectors").set_index(key)
    a = _pick(after, block, op, "zarr-vectors").set_index(key)
    rows = [
        f"| {label} | before (ms) | after (ms) | speed-up | detail after |",
        "|---:|---:|---:|---:|---|",
    ]
    for k in sorted(set(b.index) | set(a.index)):
        vb = float(b.loc[k, "value"]) if k in b.index else float("nan")
        va = float(a.loc[k, "value"]) if k in a.index else float("nan")
        sp = "—" if pd.isna(vb) or pd.isna(va) or va == 0 else f"{vb / va:,.0f}×"
        det = "" if k not in a.index else str(a.loc[k, "detail"])
        rows.append(f"| {k:,} | {_ms(vb)} | {_ms(va)} | {sp} | {det} |")
    return rows + [""]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=str(ROOT))
    args = ap.parse_args()
    root = Path(args.root)
    before, env_b = _load(root / "before")
    after, env_a = _load(root / "after")

    out = [
        "# Mesh reads: before and after",
        "",
        f"- before: zarr-vectors `{env_b.get('zarr_vectors_git')}`",
        f"- after: zarr-vectors `{env_a.get('zarr_vectors_git')}`",
        f"- machine: {env_a.get('platform')}, {env_a.get('cpu_count')} CPUs; "
        f"scratch on `{env_a.get('workdir_fstype') or env_a.get('workdir')}`, "
        "warm page cache",
        "",
        "Generated by `mesh_before_after.py` from `before/` and `after/`; "
        "every number is in those two CSVs.",
        "",
        "## Read one mesh: zarr-vectors against Neuroglancer precomputed",
        "",
        "One 144-vertex, 242-face mesh, returned with its faces by every "
        "implementation; the mean over 16 objects spread across the id range. "
        "Requests and bytes count everything the read asks its store for -- "
        "metadata included, on both sides. Precomputed rows use the same code "
        "before and after and are a control on machine drift.",
        "",
    ]
    for n in sorted(_pick(after, "mesh_precomputed", "fetch_one")["n_target"].unique()):
        out += precomputed_table(before, after, int(n))
    out += [
        "## The existing mesh series",
        "",
        "### Read one object (panel E), by vertex count",
        "",
        *series_table(before, after, "object", "fetch_one", "n_vertices", "N vertices"),
        "### Read one object against chunk count at 10⁶ vertices (panel H)",
        "",
        *series_table(before, after, "chunks", "fetch_one", "n_target", "chunks"),
        "### Read one object against fragmentation at 10⁶ vertices (panel H2)",
        "",
        *series_table(before, after, "fragments", "fetch_one", "n_target", "chunks"),
    ]
    (root / "summary.md").write_text("\n".join(out))
    print(f"wrote {root / 'summary.md'}")


if __name__ == "__main__":
    main()
