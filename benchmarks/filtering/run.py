"""Run gate G1 under CPython and Pyodide, and write the results.

    python benchmarks/filtering/run.py --pyodide-dir PATH [--real STORE]

Every set is first written to ``data/<set>/`` as .npy files, in a process
of its own: the synthetic ones generated, ``real`` read from the store given
as ``--real`` (its level 0, float32 RAS positions and ``label_id``).  Then
each set is measured in a fresh process per runtime, so each reports its own
peak memory: the process's high-water RSS under CPython, the wasm heap under
Pyodide (which only grows, so its final size is the peak).  Sets already in
``data/`` are reused.

Writes ``results/measurements.json`` (everything) and ``results/summary.md``
(the C8 gates, per set and runtime).
"""

from __future__ import annotations

import argparse
import json
import platform
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import g1  # noqa: E402

DATA = HERE / "data"
RESULTS = HERE / "results"


def cpython_worker(name: str) -> None:
    """Measure one set in this process and print its JSON."""
    import numpy as np

    from zarr_vectors_tools import filtering

    def status_mb(field: str) -> float:
        # VmHWM, unlike getrusage's ru_maxrss, is not carried over from the
        # parent across exec.
        with open("/proc/self/status") as f:
            line = next(ln for ln in f if ln.startswith(field + ":"))
        return int(line.split()[1]) / 1e3

    tg = g1.make_set(filtering, name, DATA)
    result = g1.measure(filtering, tg, memory_mb=lambda: status_mb("VmRSS"))
    result["peak_mb"] = round(status_mb("VmHWM"))
    result["runtime"] = {"name": "cpython", "python": platform.python_version(),
                         "numpy": np.__version__}
    print(json.dumps(result))


def run_one(runtime: str, name: str, pyodide_dir: str | None) -> dict:
    if runtime == "cpython":
        cmd = [sys.executable, str(HERE / "run.py"), "--worker", name]
    else:
        cmd = ["node", str(HERE / "pyodide_worker.mjs"), pyodide_dir, name, str(DATA)]
    done = subprocess.run(cmd, capture_output=True, text=True)
    lines = [ln for ln in done.stdout.splitlines() if ln.startswith("{")]
    if done.returncode != 0 or not lines:
        # The last error message, wherever it sits: Node can print it on the
        # same line as Pyodide's minified source.
        text = (done.stderr + "\n" + done.stdout).splitlines()
        errors = re.findall(r"(?:\b[\w.]*(?:Error|Exception)|Aborted)\b:? [^\n]{0,200}",
                            done.stderr + "\n" + done.stdout)
        error = errors[-1] if errors else f"exit {done.returncode}"
        log = RESULTS / f"{name}-{runtime}.log"
        log.write_text("\n".join(ln[:2000] for ln in text) + "\n")
        print(f"  {runtime} {name}: {error}", file=sys.stderr)
        return {"error": error}
    return json.loads(lines[-1])


def summary(measurements: dict) -> str:
    rows = [
        "| set | runtime | streamlines | vertices | build s | sphere ms | sphere tested "
        "| box ms | slab ms | disk ms | mask ms | ends ms | P1 ms | P3 ms | publish ms "
        "| oracle s | loaded MB | peak MB | gates met |",
        "|" + "---|" * 19,
    ]
    for name, by_runtime in measurements["sets"].items():
        for runtime, r in by_runtime.items():
            if "error" in r:
                failed = f" failed: {r['error'][:120]} |"
                rows.append(f"| {name} | {runtime} |" + " |" * 16 + failed)
                continue
            met = g1.verdict(r)
            missed = [g for g, ok in met.items() if not ok]
            rows.append(
                f"| {name} | {runtime} | {r['n_streamlines']:,} | {r['n_vertices']:,} "
                f"| {r['build_s']:.1f} | {r['sphere_ms']['median']:.1f} "
                f"| {r.get('sphere_tested', 0):,} "
                f"| {r['box_ms']['median']:.1f} | {r['slab_ms']['median']:.0f} "
                f"| {r['disk_ms']['median']:.1f} | {r['mask_ms']['median']:.1f} "
                f"| {r['endpoints_ms']['median']:.1f} | {r['p1_ms']['median']:.2f} "
                f"| {r['p3_ms']['median']:.2f} | {r['publish_ms']['median']:.2f} "
                f"| {r['oracle_sphere_s']:.1f} | {r.get('loaded_mb', '')} | {r['peak_mb']} "
                f"| {sum(met.values())}/{len(met)}"
                + (f" (missed: {', '.join(missed)})" if missed else "") + " |"
            )
    gates = ", ".join(f"{k} <= {v:g}" for k, v in g1.GATES.items())
    return (
        "# Gate G1 results\n\nMedians over 9 fresh regions (P3: 36 flips). "
        "Generated by `run.py`; see README.md.\n\n"
        f"Gates (filter plan C8): {gates}.\n\n" + "\n".join(rows) + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--pyodide-dir", help="unpacked Pyodide distribution (with numpy)")
    parser.add_argument("--real", help="a streamline store to add as the 'real' set")
    parser.add_argument("--sets", nargs="+", default=list(g1.SYNTHETIC) + ["real"])
    parser.add_argument("--runtimes", nargs="+", default=["cpython", "pyodide"])
    parser.add_argument("--worker", help=argparse.SUPPRESS)
    parser.add_argument("--prepare", help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.worker:
        cpython_worker(args.worker)
        return
    if args.prepare:
        from zarr_vectors_tools import filtering

        g1.prepare_set(filtering, args.prepare, DATA, args.real)
        if args.real:
            (DATA / "real.json").write_text(json.dumps({"store": args.real}) + "\n")
        return
    sets = []
    for name in args.sets:
        if not (DATA / name / "vertices.npy").exists():
            if name == "real" and not args.real:
                continue
            print(f"preparing {name} ...", file=sys.stderr, flush=True)
            cmd = [sys.executable, str(HERE / "run.py"), "--prepare", name]
            subprocess.run(cmd + (["--real", args.real] if name == "real" else []), check=True)
        sets.append(name)
    if "pyodide" in args.runtimes and not args.pyodide_dir:
        parser.error("--pyodide-dir is needed to run under Pyodide")
    RESULTS.mkdir(exist_ok=True)
    # Merge into earlier results, so one set or runtime can be re-measured alone.
    previous = RESULTS / "measurements.json"
    measurements: dict = json.loads(previous.read_text()) if previous.exists() else {"sets": {}}
    if (DATA / "real.json").exists():
        measurements["real_store"] = json.loads((DATA / "real.json").read_text())["store"]
    for name in sets:
        for runtime in args.runtimes:
            print(f"{name} / {runtime} ...", file=sys.stderr, flush=True)
            measurements["sets"].setdefault(name, {})[runtime] = run_one(
                runtime, name, args.pyodide_dir)
    (RESULTS / "measurements.json").write_text(json.dumps(measurements, indent=1) + "\n")
    (RESULTS / "summary.md").write_text(summary(measurements))
    print((RESULTS / "summary.md").read_text())


if __name__ == "__main__":
    main()
